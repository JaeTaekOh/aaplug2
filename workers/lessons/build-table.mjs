/* Generates src/table.js from the plugin's fixed advice table (js/lessons.js) and English built-in titles (js/i18n-en.js).
   The Worker serves titles / advice only from this generated table, never from request bodies.
   Run: node workers/lessons/build-table.mjs */
import fs from 'node:fs'; import path from 'node:path'; import vm from 'node:vm'; import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url)), JS = path.join(HERE, '..', '..', 'js');
const ctx = { window: {} }; vm.createContext(ctx);
for (const f of ['i18n-en.js', 'lessons.js']) vm.runInContext(fs.readFileSync(path.join(JS, f), 'utf8'), ctx, { filename: f });
const W = ctx.window, L = W.AAPLessons;
const en = (W.AAP_I18N && W.AAP_I18N.en) || null;
const dict = en || Object.values(W).find(v => v && typeof v === 'object' && v['rj.apple-511.t']) || {};
const table = {};
for (const [id, e] of Object.entries(L.TABLE)) {
  if (e.builtin) table[id] = { store: e.store, title: dict['rj.' + e.builtin + '.t'] || 'Built-in check ' + e.builtin, advice: dict['rj.' + e.builtin + '.w'] || 'Covered by the AA Plug 2 built-in checks.' };
  else table[id] = { store: e.store, title: e.title, advice: e.advice };
}
const playIds = Object.entries(L.TABLE).filter(([k, e]) => e.store === 'play' && !e.builtin).map(([k]) => k);
const out = `/* GENERATED by build-table.mjs from js/lessons.js — do not edit by hand. */\nexport const TABLE = ${JSON.stringify(table, null, 1)};\nexport const PLAY_IDS = ${JSON.stringify(playIds)};\n`;
fs.writeFileSync(path.join(HERE, 'src', 'table.js'), out);
console.log('table.js:', Object.keys(table).length, 'advice ids,', playIds.length, 'play policy ids, builtin titles', Object.keys(table).filter(k => k.startsWith('builtin-')).map(k => table[k].title.slice(0, 20)).join(' | '));
